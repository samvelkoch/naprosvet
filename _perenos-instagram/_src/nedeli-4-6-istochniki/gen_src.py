def voice(qid):
    q = Q[qid]; return {"q": q['q'], "a": q['a']}

def check(fr, voices):
    for k, F in fr.items():
        if k.startswith('_') or 'answers' not in F: continue
        for a, parts in F['answers'].items():
            for p in parts:
                assert p in voices[F['qid']]['a'][a], (k, a, p[:50])
        if F.get('cover_quote'):
            assert F['cover_quote']['text'] in voices[F['qid']]['a'][F['cover_quote']['author']], k

def write(week, numbers, fr):
    d = I / week / 'src'; d.mkdir(parents=True, exist_ok=True)
    voices = {F['qid']: voice(F['qid']) for k, F in fr.items() if not k.startswith('_')}
    check(fr, voices)
    N = dict(COMMON); N.update(numbers)
    for n, obj in (('numbers', N), ('personas', PERS), ('fragments', fr), ('voices', voices)):
        (d / f'{n}.json').write_text(json.dumps(obj, ensure_ascii=False, indent=1), encoding='utf-8')
    print(week, 'ok', list(fr))

